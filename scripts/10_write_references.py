"""Step 10 - generate source_references.md from verified metadata only
(Crossref/doi.org records, Wikipedia revision IDs, archived web pages, dataset catalog)."""
import csv, re
from common import *


def main():
    cr = load_json(LIT / "crossref_dois.json")
    listed = load_json(CONFIG / "doi_list.json")["dois"]
    wiki = load_json(LIT / "wikipedia_extracts_index.json")
    web = load_json(LIT / "web" / "web_fetch_log.json") if (LIT / "web" / "web_fetch_log.json").exists() else {}
    cat = list(csv.DictReader(open(OUTPUTS / "dataset_catalog.csv", encoding="utf-8")))
    L = ["# Source references", "", f"Generated by `scripts/10_write_references.py` on {RETRIEVAL_DATE}. Each DOI below was resolved this build "
         "against Crossref, or doi.org for DataCite DOIs. Titles and years come from that metadata, not from memory. "
         "Unresolved DOIs are excluded and reported in validation_report.md.", "",
         "## 1. Peer-reviewed literature and dataset DOIs (verified)", "", "| DOI | Authors (first ≤3) | Year | Title | Venue | Used for |", "|---|---|---|---|---|---|"]
    for d in listed:
        m = cr.get(d["doi"], {})
        if m.get("status") != 200:
            continue
        au = "; ".join((m.get("authors") or [])[:3]) + (" et al." if len(m.get("authors") or []) > 3 else "")
        title = re.sub(r"\s+", " ", re.sub(r"<[^>]+>", "", m.get("title") or "")).strip()
        L.append(f"| [{d['doi']}](https://doi.org/{d['doi']}) | {au or m.get('publisher','')} | {m.get('year')} | {title} | {m.get('container') or ''} | {d['used_for']} |")
    if cr.get("_corrections"):
        L += ["", "DOI corrections made during the build (caught by the citation check):", ""]
        L += [f"* `{k}`: {v}" for k, v in cr["_corrections"].items()]
    L += ["", "## 2. Agency and web pages fetched (archived in data/raw/literature/web/)", "", "| File | URL | HTTP status |", "|---|---|---|"]
    for fn, rec in web.items():
        L.append(f"| {fn} | {rec['url']} | {rec.get('status')} |")
    L += ["", "## 3. Wikipedia articles (tertiary; used for coordinates and keyword evidence only)", "",
          "| Article | Revision ID | Retrieved |", "|---|---|---|"]
    for t, m in sorted(wiki.items()):
        L.append(f"| [{t}]({m['url']}) | {m.get('lastrevid')} | {m.get('retrieved')} |")
    L += ["", "## 4. Datasets", "", "See `outputs/dataset_catalog.csv` for resolution, coverage, CRS, licence and limitations of each dataset.", "",
          "| dataset_id | name | URL | used |", "|---|---|---|---|"]
    for r in cat:
        L.append(f"| {r['dataset_id']} | {r['name']} | {r['official_url']} | {r['used_in_package']} |")
    (ROOT / "source_references.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("source_references.md written")


if __name__ == "__main__":
    main()
